"""Cotações com valores de referência do legado (zona, peso taxável, volumes, frete, seguro, total, prazo, avisos)."""

from frete import Cotador, Item, Pedido


def _cota(cep, itens, servico, cupom):
    return Cotador().cotar(Pedido(cep, tuple(Item(*i) for i in itens), servico, cupom))


def _confere(caso):
    (cep, itens, servico, cupom), esperado = caso
    c = _cota(cep, itens, servico, cupom)
    obtido = (
        c.zona,
        c.peso_taxavel_g,
        c.volumes,
        c.frete_centavos,
        c.seguro_centavos,
        c.total_centavos,
        c.prazo_dias,
        tuple(c.avisos),
    )
    assert obtido == esperado, caso[0]


